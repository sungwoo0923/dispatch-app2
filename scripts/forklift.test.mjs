// 지게차비용 계산 단위 테스트 — node scripts/forklift.test.mjs
import { forkliftApply, forkliftClear, orderProfit, forkliftPayoutGroups, forkliftRowFromSheet, fkPresetKey, forkliftSummary } from "../src/forkliftCore.js";
import { fareFormChange } from "../src/fareRulesCore.js";

let pass = 0, fail = 0;
const eq = (a, b, msg) => { if (JSON.stringify(a) === JSON.stringify(b)) pass++; else { fail++; console.log("  ✗", msg, "→", JSON.stringify(a), "기대", JSON.stringify(b)); } };
const set = (o, k, v) => forkliftApply(o, { ...o, [k]: v }, k);
const base = { 청구운임: "500000", 기사운임: "400000", 수수료: "100000" };

// 1) 기사 부담(기본)
let o = set(base, "지게차비용", "100000");
eq([o.청구운임, o.기사운임, o.수수료, o.지게차기사차감], ["500000", "300000", "100000", 100000], "기사 부담: 기사 300,000 · 수익 100,000");
eq(orderProfit(o), 100000, "기사 부담 수익");
// 금액 바꾸기 120,000
o = set(o, "지게차비용", "120000");
eq([o.기사운임, o.수수료], ["280000", "100000"], "금액 변경 시 다시 계산");
// 2) 회사 부담으로 바꾸기
o = set(o, "지게차부담", "회사");
eq([o.청구운임, o.기사운임, o.수수료, o.지게차기사차감], ["500000", "400000", "-20000", 0], "회사 부담: 기사 원래대로 · 수익 −20,000");
// 3) 청구 추가
o = set(o, "지게차부담", "청구");
eq([o.청구운임, o.기사운임, o.수수료, o.지게차청구추가], ["620000", "400000", "100000", 120000], "추가 청구: 청구 620,000");
// 다시 기사 부담
o = set(o, "지게차부담", "기사");
eq([o.청구운임, o.기사운임, o.지게차청구추가], ["500000", "280000", 0], "청구 → 기사 부담 되돌림");
// 회사 부담에서 끄기 — 수익 원래대로
{ const c = forkliftClear(set(set(base, "지게차비용", "100000"), "지게차부담", "회사")); eq([c.청구운임, c.기사운임, c.수수료], ["500000", "400000", "100000"], "회사 부담 끄기 → 수익 복원"); }
// 4) 끄기 복원
o = forkliftClear(o);
eq([o.청구운임, o.기사운임, o.수수료, o.지게차비용, o.지게차기사차감], ["500000", "400000", "100000", "", 0], "지게차 끄면 원래 운임으로");
// 5) 0·빈값
eq(set(base, "지게차비용", "").기사운임, "400000", "빈 금액은 변화 없음");
eq(set(base, "지게차비용", "0").수수료, "100000", "0원은 변화 없음");
eq(orderProfit({ 청구운임: 300000, 기사운임: 250000 }), 50000, "지게차 없는 오더 수익");
// 6) 사람이 기사운임 직접 고침 → 그 값 유지, 수익은 지게차 빼고
o = set(base, "지게차비용", "100000");
o = set(o, "기사운임", "250000");
eq([o.기사운임, o.수수료], ["250000", "150000"], "기사운임 직접 수정 유지");
// 청구운임 직접 수정
o = set(o, "청구운임", "550000");
eq([o.청구운임, o.기사운임, o.수수료], ["550000", "250000", "200000"], "청구운임 수정 → 수익만 다시");
// 7) 운임구분(7%)과 함께 — 운임구분이 기사운임을 다시 계산하면 지게차를 다시 뺀다
const rules = [{ name: "월대", type: "percent", value: 7, active: true }];
let f = fareFormChange({ 청구운임: "500000" }, "운임구분", "월대", rules);
eq([f.기사운임, f.수수료], ["465000", "35000"], "운임구분 7% 계산");
let g = forkliftApply(f, { ...f, 지게차비용: "100000" }, "지게차비용");
eq([g.기사운임, g.수수료], ["365000", "35000"], "운임구분 + 지게차(기사 부담)");
let h = fareFormChange(g, "청구운임", "600000", rules);
eq([h.기사운임, h.수수료], ["458000", "42000"], "청구 바꿔 운임구분이 다시 계산해도 지게차 다시 차감");
let h2 = fareFormChange(h, "운임구분수수료율", "10", rules);
eq([h2.기사운임, h2.수수료], ["440000", "60000"], "수수료율 10%로 바꿔도 지게차 유지");
// 8) 숫자형 저장
const n = forkliftApply({ 청구운임: 500000, 기사운임: 400000 }, { 청구운임: 500000, 기사운임: 400000, 지게차비용: 100000 }, "지게차비용", { asString: false });
eq([n.기사운임, n.수수료], [300000, 100000], "숫자형 저장");
// 9) 지급 묶음
const groups = forkliftPayoutGroups([
  { 지게차비용: 100000, 지게차기사ID: "a", 지게차기사명: "김지게" },
  { 지게차비용: 50000, 지게차기사ID: "a", 지게차기사명: "김지게", 지게차지급완료: true },
  { 지게차비용: 70000, 지게차기사ID: "b", 지게차기사명: "박지게" },
  { 지게차비용: 90000, 지게차기사ID: "b", 배차상태: "배차취소" },
  { 청구운임: 1 },
]);
eq(groups.map((x) => [x.name, x.total, x.paid, x.unpaid, x.count]), [["김지게", 150000, 50000, 100000, 2], ["박지게", 70000, 0, 70000, 1]], "지게차 기사별 지급 합계(취소 제외)");
// 10) 업로드 줄 검사
eq(forkliftRowFromSheet({ 이름: "홍길동", 전화번호: "010-1234-5678", 은행명: "국민", 계좌번호: "123-45" }).row.은행, "국민", "은행명 열도 인식");
eq(forkliftRowFromSheet({ 전화번호: "0101" }).errors, ["이름 없음", "전화번호 자리수"], "업로드 오류 표시");
eq(fkPresetKey({ 거래처명: "경동 ", 상차지명: "경동 본사" }), "경동__경동본사", "상차지 기억 키");
eq(forkliftSummary(set(base, "지게차비용", "100000")), "청구 500,000 · 기사 300,000 · 지게차 100,000 · 수익 100,000", "요약 문구");

console.log(`지게차비용 단위 테스트: 통과 ${pass} · 실패 ${fail}`);
process.exit(fail ? 1 : 0);
